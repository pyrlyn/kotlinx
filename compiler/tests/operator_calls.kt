// Operators of numbers and strings in method-call form.
fun main() {
    println(1.plus(2)); println(5L.minus(1L)); println(2.0.times(1.5)); println(7.div(2)); println(7.rem(3))
    println("a".plus("b")); println(3.equals(3)); println("x".equals("y"))
    for (i in 1.rangeTo(3)) print(i)
    println()
}
