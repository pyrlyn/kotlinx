#!/usr/bin/env python3
"""Generates the sources of the FFI benchmark: shared C, KotlinX (external fun) and Kotlin/Native (cinterop) mains.
`gen.py <out> <many>`: <many> extra C functions fb_f<i> (the "many functions" case)."""
import sys, os
out, many = sys.argv[1], int(sys.argv[2])
os.makedirs(out, exist_ok=True)
with open(f"{out}/many.h", "w") as h, open(f"{out}/many.c", "w") as c:
    h.write("#include <stdint.h>\n"); c.write('#include "many.h"\n')
    for i in range(many):
        h.write(f"int64_t fb_f{i}(int64_t x);\n"); c.write(f"int64_t fb_f{i}(int64_t x) {{ return x + {i}; }}\n")
N = 100_000_000
body = f"""
fun main() {{
    // warm-up
    var w = 0L; var j = 0L
    while (j < 1000000L) {{ w = fb_add(w, j); j++ }}
    val t0 = fb_now_ns()
    var acc = 0L; var i = 0L
    while (i < {N}L) {{ acc = fb_add(acc, i); i++ }}
    val t1 = fb_now_ns()
    var d = 0.0; i = 0L
    while (i < {N}L) {{ d = fb_scale(d, 0.5); i++ }}
    val t2 = fb_now_ns()
    val big = fb_big_new()
    var s = 0L; i = 0L
    while (i < {N // 10}L) {{ s = fb_big_sum(big, s and 1023L); i++ }}
    val t3 = fb_now_ns()
    var m = 0L; i = 0L
    while (i < {N // many if many else 0}L) {{
{chr(10).join(f"        m = fb_f{k}(m)" for k in range(many))}
        i++
    }}
    val t4 = fb_now_ns()
    println("check=" + (acc + w).toString() + " " + d.toString() + " " + s.toString() + " " + m.toString())
    println("add_ns=" + ((t1 - t0).toDouble() / {N}.0).toString())
    println("scale_ns=" + ((t2 - t1).toDouble() / {N}.0).toString())
    println("bigptr_ns=" + ((t3 - t2).toDouble() / {N // 10}.0).toString())
    println("many_ns=" + ((t4 - t3).toDouble() / {(N // many) * many if many else 1}.0).toString())
}}
"""
decls = ["external fun fb_add(acc: Long, x: Long): Long", "external fun fb_scale(acc: Double, k: Double): Double",
         "external fun fb_now_ns(): Long", "external fun fb_big_new(): CPointer", "external fun fb_big_sum(p: CPointer, salt: Long): Long"]
decls += [f"external fun fb_f{k}(x: Long): Long" for k in range(many)]
open(f"{out}/kx.kt", "w").write("// generated by bench/ffi/gen.py\n" + "\n".join(decls) + "\n" + body)
open(f"{out}/kn.kt", "w").write("// generated by bench/ffi/gen.py\n@file:OptIn(kotlinx.cinterop.ExperimentalForeignApi::class)\nimport fb.*\n" + body)
here = os.path.dirname(os.path.abspath(__file__))
open(f"{out}/fb.def", "w").write(f"headers = {here}/ffi_bench.h {out}/many.h\nheaderFilter = {here}/ffi_bench.h {out}/many.h\n")
